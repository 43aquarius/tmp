#!/bin/bash
# 批量生成《来自海边的信》分镜关键帧
# 用法: bash gen_frames.sh [起始编号] [结束编号]

DIR=/home/z/my-project/dalian_video
OUT=$DIR/frames
mkdir -p $OUT

START=${1:-1}
END=${2:-18}

# 角色一致性锚点描述（每镜必带）
LANG="一只毛茸茸圆滚滚的白色小海鸥精灵，琥珀色大圆眼睛，头顶一根小呆毛，脖子系天蓝色浪花图案围巾，翅尖淡蓝色，小巧橙色鸟喙"
GIRL="一位20岁出头的中国女孩，齐肩黑色短发带空气刘海，穿米色针织开衫，清秀温柔"
STYLE="治愈系动画电影风格，新海诚式唯美光影，电影级构图，柔和景深，通透色彩，竖版9:16画面"

declare -A PROMPTS
PROMPTS[1]="$STYLE。深夜异乡大都市，灰蓝冷色调，雨夜，霓虹灯反射在湿漉漉的街道上，$GIRL 打着透明伞独自走出写字楼，疲惫孤独的背影，玻璃幕墙冷光，压抑清冷氛围"
PROMPTS[2]="$STYLE。深夜出租屋窗台，暖黄台灯光晕，一根泛着柔光的白色羽毛正飘落在木质窗台上，化作一封微微发光的米白色信封，窗外是模糊的城市霓虹夜景，梦幻光粒子，奇幻治愈氛围"
PROMPTS[3]="$STYLE。特写镜头：米白色复古信封平放在木桌上，旁边放着一根洁白羽毛，晨光斜照，浅景深，信封表面留白干净（无文字），温暖色调，电影感静物"
PROMPTS[4]="$STYLE。阳光倾泻的火车站出站口广场，明亮暖金色调，$LANG 站立在蓝色栏杆上歪着头好奇张望，$GIRL 拖着行李箱惊喜地看着它，背景有大连火车站建筑轮廓，通透阳光，重逢的喜悦氛围"
PROMPTS[5]="$STYLE。城市街道上，$LANG 张开翅膀低空飞翔引路，$GIRL 拖着行李箱笑着奔跑跟随，阳光穿过行道树洒下斑驳光点，动感构图，欢快明亮"
PROMPTS[6]="$STYLE。大连星海广场清晨，辽阔的海滨广场，$GIRL 向天空抛洒面包屑，成群白色海鸥盘旋俯冲飞舞，远处海面波光粼粼，$LANG 在她身旁飞舞，蓝天白云风筝，暖金晨光，自由欢快"
PROMPTS[7]="$STYLE。大连百年老电车车厢内部，深色木质座椅与车厢，复古黄铜拉环，午后阳光透过车窗洒落斑驳光影，$GIRL 坐在木质座椅上靠窗微笑看着窗外流动的老街风景，怀旧温柔，胶片质感"
PROMPTS[8]="$STYLE。大连中山广场，环形广场被欧式古典建筑环绕，绿色穹顶与石柱立面，广场上鸽子踱步，阳光在建筑上流转，海风轻拂，典雅城市风光大远景"
PROMPTS[9]="$STYLE。大连老城巷口的传统小吃摊，铁板上金黄色焖子块滋滋冒油腾起热气，摊主奶奶慈祥微笑着递给 $GIRL 一盘淋满芝麻酱的焖子，热气腾腾的烟火气，暖黄色调，食欲诱人，市井温情"
PROMPTS[10]="$STYLE。大连滨海路木栈道悬崖观景台，$GIRL 倚着栏杆远眺蔚蓝大海，海风吹起发丝，远处海面辽阔有一座白色灯塔，浪花拍打礁石，天海一色，壮丽治愈"
PROMPTS[11]="$STYLE。暖金色回忆色调，柔焦梦幻滤镜，小小的女孩牵着慈祥奶奶的手在星海广场喂海鸥，海鸥群环绕飞舞，夕阳逆光剪影温馨画面， nostalgic 怀旧氛围，温暖幸福"
PROMPTS[12]="$STYLE。大连东港商务区威尼斯水城黄昏，河道中停着贡多拉小船，欧式彩色尖顶建筑倒映在金色水面，夕阳余晖洒满河道，浪漫唯美"
PROMPTS[13]="$STYLE。大连星海湾跨海大桥夜景，蓝色夜幕下大桥灯光璀璨如琴弦横跨海面，城市灯光在海面倒映成星河，深蓝夜空，大气恢弘"
PROMPTS[14]="$STYLE。黄昏海边沙滩，$GIRL 坐在沙滩上轻轻打开一封米白色信纸，夕阳金光洒满海面，信纸泛着微微柔光，逆光唯美，安静治愈"
PROMPTS[15]="$STYLE。特写：泛黄信纸在夕阳暖光中，纸张表面干净留白（无文字），旁边放着白色羽毛，光线柔和，浅景深，电影质感"
PROMPTS[16]="$STYLE。夕阳海边，$LANG 轻轻落在 $GIRL 的肩膀上，女孩微微侧头与之对视微笑，金色逆光剪影轮廓，温馨治愈画面"
PROMPTS[17]="$STYLE。清晨日出时分的海滨广场，$GIRL 微笑着打电话，$LANG 站在她的手臂上，朝阳从海平面升起金光万丈，远处海鸥群飞过，希望与新生"
PROMPTS[18]="$STYLE。$LANG 率领一大群白色海鸥飞过金色朝阳照耀的海面，壮丽大远景，翅膀剪影，光斑闪烁，自由辽阔，史诗感收尾"

for i in $(seq $START $END); do
  OUTFILE=$(printf "$OUT/scene_%02d.png" $i)
  if [ -f "$OUTFILE" ]; then
    echo "[$i/18] 已存在，跳过"
    continue
  fi
  echo "[$i/18] 生成: ${PROMPTS[$i]:0:50}..."
  for retry in 1 2 3 4 5; do
    z-ai image -p "${PROMPTS[$i]}" -o "$OUTFILE" -s 768x1344 2>&1 | tail -1
    if [ -f "$OUTFILE" ]; then
      echo "[$i/18] ✅ 完成"
      break
    else
      WAIT=$((retry * 20))
      echo "[$i/18] ❌ 第${retry}次失败，${WAIT}秒后重试..."
      sleep $WAIT
    fi
  done
  sleep 8
done
echo "=== 批量生成完毕 ==="
ls -la $OUT/
